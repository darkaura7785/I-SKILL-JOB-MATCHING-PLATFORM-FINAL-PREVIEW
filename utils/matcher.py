def normalize_skill(skill: str) -> str:
    """Normalises a skill string for case-insensitive comparison."""
    return skill.strip().lower()


def _age_suitability(age: float, role: Dict[str, Any]) -> float:
    """
    Returns age suitability score (0.0-1.0) based on role's physical demand and max_recommended_age.

    - Low physical_demand: always 1.0 (no age filter)
    - Moderate physical_demand: gradual decline near the cutoff
    - High physical_demand: hard cutoff at max_recommended_age
    """
    physical_demand = role.get("physical_demand", "low")
    max_recommended_age = role.get("max_recommended_age")

    # Low physical demand: no age restriction
    if physical_demand == "low" or max_recommended_age is None:
        return 1.0

    if physical_demand == "high":
        # Hard cutoff at max_recommended_age
        if age >= max_recommended_age:
            return 0.0
        # Gentle decline as age approaches the cutoff
        ideal_age = max(18, max_recommended_age - 15)
        if age <= ideal_age:
            return 1.0
        return max(0.0, 1.0 - ((age - ideal_age) / (max_recommended_age - ideal_age)))

    # Moderate physical demand: gradual decline near the cutoff
    if age >= max_recommended_age:
        return max(0.0, 1.0 - ((age - max_recommended_age) / 10.0))
    ideal_age = max(18, max_recommended_age - 10)
    if age <= ideal_age:
        return 1.0
    return max(0.0, 1.0 - ((age - ideal_age) / (max_recommended_age - ideal_age)))


def _gender_suitability(gender: str, role: Dict[str, Any]) -> float:
    """
    Returns gender suitability score (0.7-1.0) based on role's gender_context.

    - neutral: always 1.0
    - female_preferred_regulatory: 1.0 if female, 0.7 otherwise
    - male_preferred_regulatory: 1.0 if male, 0.7 otherwise
    """
    gender_context = role.get("gender_context", "neutral")
    gender = gender.lower().strip() if gender else "neutral"

    if gender_context == "neutral":
        return 1.0
    elif gender_context == "female_preferred_regulatory":
        return 1.0 if gender == "female" else 0.7
    elif gender_context == "male_preferred_regulatory":
        return 1.0 if gender == "male" else 0.7
    else:
        return 1.0


def compute_role_compatibility(
    user_skills: List[str],
    user_experience: float = 0.0,
    user_education: str = "Not Specified",
    internship_months: float = 0.0,
    user_age: float = 0.0,
    user_gender: str = "neutral",
    role: Dict[str, Any] = None,
) -> Dict[str, Any]:
    """
    Computes a fine-grained compatibility score between candidate and a role.

    Weights
    -------
    60%  Required skills overlap
    18%  Preferred skills overlap
    10%  Experience alignment  (professional + 0.4× internship credit)
     5%  Education alignment
     4%  Age suitability
     3%  Gender suitability

    ``internship_months`` is the internship duration in months.  It counts
    partially (40 %) toward the experience threshold, converted from months
    to years first.
    """
    if role is None:
        return {}

    user_norm   = {normalize_skill(s) for s in user_skills}
    req_norm    = {normalize_skill(s) for s in role["required_skills"]}
    pref_norm   = {normalize_skill(s) for s in role.get("preferred_skills", [])}

    # ── Skill overlaps ───────────────────────────────────────────────────────
    matched_req  = req_norm  & user_norm
    matched_pref = pref_norm & user_norm

    req_ratio  = len(matched_req)  / len(req_norm)  if req_norm  else 1.0
    pref_ratio = len(matched_pref) / len(pref_norm) if pref_norm else 0.5

    # ── Experience factor ────────────────────────────────────────────────────
    min_exp = role.get("min_experience_years", 0)
    # Give partial credit for internship (40 %)
    effective_exp = user_experience + (internship_months / 12.0) * 0.4

    if min_exp == 0:
        exp_score = 1.0
    elif effective_exp >= min_exp:
        exp_score = 1.0
    elif effective_exp > 0:
        exp_score = max(0.4, effective_exp / min_exp)
    else:
        exp_score = 0.3

    # ── Education factor ─────────────────────────────────────────────────────
    edu_score = EDU_WEIGHTS.get(user_education, 0.60)

    # ── Age suitability ──────────────────────────────────────────────────────
    age_score = _age_suitability(user_age, role)

    # ── Gender suitability ───────────────────────────────────────────────────
    gender_score = _gender_suitability(user_gender, role)

    # ── Composite score ──────────────────────────────────────────────────────
    raw = (
        (req_ratio * 60.0)
        + (pref_ratio * 18.0)
        + (exp_score * 10.0)
        + (edu_score * 5.0)
        + (age_score * 4.0)
        + (gender_score * 3.0)
    )
    compatibility_score = round(min(99.0, max(12.0, raw)), 1)

    # ── Build display lists ───────────────────────────────────────────────────
    all_role_skills = role["required_skills"] + role.get("preferred_skills", [])
    matched_display: List[str] = []
    missing_display: List[str] = []

    for s in all_role_skills:
        if normalize_skill(s) in user_norm:
            if s not in matched_display:
                matched_display.append(s)
        elif s in role["required_skills"] and s not in missing_display:
            missing_display.append(s)

    return {
        "role_id": role["role_id"],
        "title": role["title"],
        "category": role["category"],
        "description": role["description"],
        "compatibility_score": compatibility_score,
        "matched_skills": matched_display,
        "missing_skills": missing_display[:5],
        "required_skills_count": len(role["required_skills"]),
        "matched_required_count": len(matched_req),
        "min_experience": min_exp,
        "typical_salary_lpa": role.get("typical_salary_lpa", "—"),
        "age_score": round(age_score, 2),
        "gender_score": round(gender_score, 2),
    }


def rank_top_roles(
    user_skills: List[str],
    user_experience: float = 0.0,
    user_education: str = "Not Specified",
    internship_months: float = 0.0,
    user_age: float = 0.0,
    user_gender: str = "neutral",
    top_n: int = 4,
) -> List[Dict[str, Any]]:
    """
    Scores every role profile and returns the top_n best matches
    sorted descending by compatibility_score.

    ``internship_months`` is the internship duration in months.
    """
    scored = [
        compute_role_compatibility(
            user_skills=user_skills,
            user_experience=user_experience,
            user_education=user_education,
            internship_months=internship_months,
            user_age=user_age,
            user_gender=user_gender,
            role=role,
        )
        for role in ROLE_PROFILES
    ]
    scored.sort(key=lambda x: x["compatibility_score"], reverse=True)
    return scored[:top_n]
